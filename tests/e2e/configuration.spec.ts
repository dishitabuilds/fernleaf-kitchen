import { expect, test, type Page } from '@playwright/test';
import type { CompanyResponse, EmployeeResponse, MenuCategory, PageResponse, PriceTierRecord, SettingsResponse } from '@fernleaf/contracts';

test.use({ timezoneId: 'America/Los_Angeles' });

async function login(page: Page) {
  await page.goto('/login');
  await page.getByLabel('Email address').fill('admin@test.com');
  await page.getByLabel('Password', { exact: true }).fill('Test@1234');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
}
const unique = () => `Browser ${Date.now()} ${Math.floor(Math.random() * 10000)}`;
async function createCompany(page: Page, name: string, domain: string) {
  await page.goto('/companies');
  await page.getByRole('button', { name: 'Add company', exact: true }).click();
  const form = page.getByRole('form', { name: 'Add company', exact: true });
  await form.getByLabel('Company name', { exact: false }).fill(name);
  await form.getByLabel('Billing name', { exact: false }).fill(name);
  await form.getByLabel('Billing email', { exact: false }).fill(`billing@${domain}`);
  await form.getByLabel('Billing contact name', { exact: false }).fill('Browser accounts');
  await form.getByLabel('Billing address', { exact: false }).fill('42 Browser Street, Bengaluru');
  await form.getByLabel('Company email domains', { exact: false }).fill(domain);
  await form.getByLabel('First employee / owner name', { exact: false }).fill(`${name} owner`);
  await form.getByLabel('First employee / owner email', { exact: false }).fill(`owner@${domain}`);
  await form.getByLabel('Street address', { exact: false }).fill('42 Browser Street');
  await form.getByLabel('City', { exact: false }).fill('Bengaluru');
  await form.getByLabel('State / region', { exact: false }).fill('Karnataka');
  await form.getByLabel('Postal code', { exact: false }).fill('560001');
  await form.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(form).toHaveCount(0);
  const result = await page.request.get(`/api/v1/companies?search=${encodeURIComponent(name)}`);
  const list = await result.json() as PageResponse<CompanyResponse>;
  expect(list.items).toHaveLength(1);
  return list.items[0];
}

